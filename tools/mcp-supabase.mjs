/**
 * Dev-only helper: talk to the read-only `supabase-kodi` MCP server over stdio.
 *
 * The MCP tools are not exposed in every session, so this script drives the
 * configured server directly with JSON-RPC over stdin/stdout.
 *
 *   node tools/mcp-supabase.mjs tools/list
 *   node tools/mcp-supabase.mjs list_tables '{"schemas":["public"]}'
 *   node tools/mcp-supabase.mjs execute_sql '{"query":"select 1"}'
 *
 * The access token is read from the CLI config file and never printed.
 * The server runs with --read-only, so only read operations are possible.
 */
import { spawn } from "node:child_process";
import { readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const redact = (s) =>
  String(s).replace(/sbp_[A-Za-z0-9]+/g, "[redacted]").replace(/eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+/g, "[redacted]");

const configPath = join(homedir(), ".zcode", "cli", "config.json");
let srv;
try {
  const config = JSON.parse(readFileSync(configPath, "utf8"));
  srv = config?.mcp?.servers?.["supabase-kodi"];
} catch (e) {
  console.error(`cannot read MCP config at ${configPath}: ${redact(e.message)}`);
  process.exit(1);
}
if (!srv) {
  console.error("supabase-kodi MCP server not configured");
  process.exit(1);
}

const tool = process.argv[2] ?? "tools/list";
let toolArgs = {};
if (process.argv[3]) {
  // Allow @path/to/args.json to avoid command-line length/escaping limits
  // (needed for multi-KB migration SQL). The file may itself be generated by
  // a script so secrets never appear in argv.
  const raw = process.argv[3].startsWith("@")
    ? readFileSync(process.argv[3].slice(1), "utf8")
    : process.argv[3];
  try {
    toolArgs = JSON.parse(raw);
  } catch {
    console.error("third argument must be valid JSON (or @file with JSON)");
    process.exit(1);
  }
}

const TIMEOUT_MS = Number(process.env.MCP_TIMEOUT_MS ?? 280000);

let child;
const childEnv = { ...process.env, ...(srv.env ?? {}) };
// Set MCP_WRITABLE=1 to spawn WITHOUT --read-only, unlocking apply_migration
// and deploy_edge_function. Use only for applying verified migration files and
// deploying reviewed function code — never ad-hoc DDL.
const args = [...(srv.args ?? [])];
if (process.env.MCP_WRITABLE === "1") {
  const i = args.indexOf("--read-only");
  if (i >= 0) args.splice(i, 1);
  console.error("writable MCP mode: --read-only removed");
}
const exe = String(srv.command).replace(/\//g, "\\");
const cmdline = `"${exe}" ${args.map((a) => `"${a}"`).join(" ")}`;
if (process.env.MCP_DEBUG) console.error(`spawning: ${redact(cmdline)}`);
if (process.platform === "win32") {
  child = spawn(cmdline, {
    env: childEnv,
    stdio: ["pipe", "pipe", "pipe"],
    shell: true,
    windowsHide: true,
  });
} else {
  child = spawn(cmdline, { env: childEnv, stdio: ["pipe", "pipe", "pipe"], shell: "/bin/sh" });
}

let stderr = "";
child.stderr.on("data", (d) => {
  stderr += d.toString();
});

let buffer = "";
const pending = new Map();
let nextId = 1;

function send(msg) {
  child.stdin.write(JSON.stringify(msg) + "\n");
}

function request(method, params) {
  const id = nextId++;
  return new Promise((resolve, reject) => {
    pending.set(id, { resolve, reject });
    send({ jsonrpc: "2.0", id, method, params });
  });
}

child.stdout.on("data", (d) => {
  buffer += d.toString();
  let idx;
  while ((idx = buffer.indexOf("\n")) >= 0) {
    const line = buffer.slice(0, idx).trim();
    buffer = buffer.slice(idx + 1);
    if (!line) continue;
    let msg;
    try {
      msg = JSON.parse(line);
    } catch {
      continue; // non-JSON log line
    }
    if (msg.id != null && pending.has(msg.id)) {
      const { resolve, reject } = pending.get(msg.id);
      pending.delete(msg.id);
      if (msg.error) reject(new Error(`MCP error ${msg.error.code}: ${msg.error.message}`));
      else resolve(msg.result);
    }
  }
});

const timer = setTimeout(() => {
  console.error("timed out waiting for MCP server");
  console.error(redact(stderr.slice(-2000)));
  child.kill();
  process.exit(1);
}, TIMEOUT_MS);

child.on("error", (e) => {
  clearTimeout(timer);
  console.error(`failed to start MCP server: ${redact(e.message)}`);
  process.exit(1);
});

try {
  const init = await request("initialize", {
    protocolVersion: "2024-11-05",
    capabilities: {},
    clientInfo: { name: "zcode-dev-helper", version: "1.0.0" },
  });
  if (process.env.MCP_DEBUG) console.error(`server: ${init?.serverInfo?.name} ${init?.serverInfo?.version ?? ""}`);
  send({ jsonrpc: "2.0", method: "notifications/initialized" });

  let result;
  if (tool === "tools/list") {
    result = await request("tools/list", {});
  } else {
    result = await request("tools/call", { name: tool, arguments: toolArgs });
  }
  clearTimeout(timer);
  child.kill();
  console.log(JSON.stringify(result, null, 2));
} catch (e) {
  clearTimeout(timer);
  console.error(`MCP call failed: ${redact(e.message)}`);
  if (stderr) console.error(redact(stderr.slice(-2000)));
  child.kill();
  process.exit(1);
}
